//! Development server: the real UI (`ui/`) with the real backend, in a normal browser.
//!
//! `cargo run --features devserver --bin devserver [-- <ui-dir> [port]]`, then open
//! `http://127.0.0.1:<port>/`. It replaces `mock.js` with a small bridge that sends every command
//! to `POST /invoke`, so the page can be driven (for example by an automated browser) against real
//! archives without a window appearing. Dialogs are answered from a queue the test fills:
//! `window.__dialogs.push("/path")` before clicking.
//!
//! Only for development: it listens on 127.0.0.1, accepts only requests with the custom header
//! `X-Rgrf-Dev` (a web page on another origin cannot send it without a CORS preflight, which is not
//! answered) and a `Host` of 127.0.0.1/localhost. Long jobs run to the end without progress events.

use std::collections::HashMap;
use std::io::{BufRead, BufReader, Read, Write};
use std::net::{TcpListener, TcpStream};
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};

use rgrf_core::progress::Control;
use rustygrf_gui_lib::backend::{self, BuildRequest, MergeRequest, Session};
use rustygrf_gui_lib::saving;
use serde::de::DeserializeOwned;
use serde_json::{Value, json};

const BRIDGE_JS: &str = r#"// generated by devserver: the page talks to the real backend over HTTP
window.__dialogs = [];
const call = async (cmd, args) => {
  const r = await fetch("/invoke", { method: "POST", headers: { "X-Rgrf-Dev": "1", "Content-Type": "application/json" }, body: JSON.stringify({ cmd, args: args || {} }) });
  const j = await r.json();
  if (j.error !== undefined) throw j.error;
  return j.ok;
};
const next = () => (window.__dialogs.length ? window.__dialogs.shift() : null);
window.__TAURI__ = { core: { invoke: call }, dialog: { open: async () => next(), save: async () => next() }, event: { listen: () => {} } };
"#;

type State = Arc<Mutex<Option<Session>>>;

fn arg<T: DeserializeOwned>(args: &Value, key: &str) -> Result<T, String> {
    serde_json::from_value(args.get(key).cloned().unwrap_or(Value::Null))
        .map_err(|e| format!("argument '{key}': {e}"))
}

fn to_json<T: serde::Serialize>(v: T) -> Result<Value, String> {
    serde_json::to_value(v).map_err(|e| e.to_string())
}

fn with<T>(state: &State, f: impl FnOnce(&mut Session) -> Result<T, String>) -> Result<T, String> {
    let mut g = state.lock().map_err(|_| "state is locked")?;
    f(g.as_mut().ok_or("no archive is open")?)
}

fn invoke(state: &State, cmd: &str, a: &Value) -> Result<Value, String> {
    let none = Control::default();
    match cmd {
        "open_archive" => {
            let key = a
                .get("password")
                .and_then(|p| p.as_str())
                .filter(|p| !p.is_empty())
                .map(|p| rgrf_core::grfcrypt::key_from_password(p).map_err(|e| e.to_string()))
                .transpose()?;
            let mut s =
                Session::open_with(&PathBuf::from(arg::<String>(a, "path")?), key.as_ref())?;
            // drafts below RGRF_DRAFT_DIR, or the temporary folder
            s.set_draft_root(Some(std::env::var_os("RGRF_DRAFT_DIR").map_or_else(
                || std::env::temp_dir().join("rustygrf-drafts"),
                PathBuf::from,
            )));
            let info = s.info();
            *state.lock().map_err(|_| "state is locked")? = Some(s);
            to_json(info)
        }
        "search" => with(state, |s| to_json(s.search(&arg::<String>(a, "query")?))),
        "set_view" => with(state, |s| {
            let spec: rustygrf_gui_lib::view::ViewSpec = arg(a, "spec")?;
            to_json(s.set_view(arg(a, "view")?, spec)?)
        }),
        "page_view" => with(state, |s| {
            let limit: usize = arg(a, "limit")?;
            to_json(s.page_view(arg(a, "view")?, arg(a, "offset")?, limit.min(500)))
        }),
        // there is no native menu in the browser
        "set_menu_labels" => Ok(serde_json::Value::Null),
        "thumbnails" => with(state, |s| {
            let entries: Vec<usize> = arg(a, "entries")?;
            to_json(s.thumbnails(&entries, arg(a, "side")?))
        }),
        "tree_toggle" => with(state, |s| {
            to_json(s.tree_toggle(arg(a, "view")?, &arg::<String>(a, "path")?)?)
        }),
        "tree_set_all" => with(state, |s| {
            to_json(s.tree_set_all(arg(a, "view")?, arg(a, "open")?)?)
        }),
        "locate" => with(state, |s| {
            let folder: Option<String> = arg(a, "folder")?;
            to_json(s.locate(arg(a, "view")?, arg(a, "entry")?, folder.as_deref())?)
        }),
        "folder_entries" => with(state, |s| {
            to_json(s.folder_entries(arg(a, "view")?, &arg::<String>(a, "path")?)?)
        }),
        "page" => with(state, |s| {
            to_json(s.page(arg(a, "offset")?, arg::<usize>(a, "limit")?.min(500)))
        }),
        "set_names" => with(state, |s| {
            s.set_names(&arg::<String>(a, "mode")?)?;
            to_json(s.filtered().len())
        }),
        "details" => with(state, |s| to_json(s.details(arg(a, "index")?)?)),
        "preview" => with(state, |s| {
            to_json(s.preview(arg(a, "index")?, arg(a, "action")?)?)
        }),
        "extract_map" => with(state, |s| {
            to_json(s.extract_map(
                arg(a, "index")?,
                &PathBuf::from(arg::<String>(a, "dest")?),
                arg(a, "rename")?,
                &arg::<Option<Vec<String>>>(a, "skip")?.unwrap_or_default(),
            )?)
        }),
        "save_picture" => to_json(backend::save_picture(
            &PathBuf::from(arg::<String>(a, "path")?),
            &arg::<String>(a, "png")?,
        )?),
        "extract" => with(state, |s| {
            let indices: Vec<usize> = arg(a, "indices")?;
            let list = if indices.is_empty() {
                s.filtered().to_vec()
            } else {
                indices
            };
            to_json(s.extract(
                &list,
                &PathBuf::from(arg::<String>(a, "dest")?),
                arg(a, "rename")?,
            )?)
        }),
        "verify" => with(state, |s| to_json(s.verify(arg(a, "decode")?)?)),
        "stage_replace" => with(state, |s| {
            s.stage_replace(arg(a, "index")?, &PathBuf::from(arg::<String>(a, "file")?))?;
            to_json(s.pending())
        }),
        "stage_add" => with(state, |s| {
            s.stage_add(
                &arg::<String>(a, "path")?,
                &PathBuf::from(arg::<String>(a, "file")?),
            )?;
            to_json(s.pending())
        }),
        "stage_remove" => with(state, |s| {
            let indices: Vec<usize> = arg(a, "indices")?;
            let list = if indices.is_empty() {
                s.filtered().to_vec()
            } else {
                indices
            };
            s.stage_remove(&list)?;
            to_json(s.pending())
        }),
        "stage_spr_image" => with(state, |s| {
            s.stage_spr_image(
                arg(a, "index")?,
                arg(a, "frame")?,
                &PathBuf::from(arg::<String>(a, "png")?),
            )?;
            to_json(s.pending())
        }),
        "stage_spr_add" => with(state, |s| {
            s.stage_spr_add(arg(a, "index")?, &PathBuf::from(arg::<String>(a, "png")?))?;
            to_json(s.pending())
        }),
        "stage_spr_remove" => with(state, |s| {
            s.stage_spr_remove(arg(a, "index")?, arg(a, "frame")?)?;
            to_json(s.pending())
        }),
        "stage_spr_palette" => with(state, |s| {
            s.stage_spr_palette(arg(a, "index")?, &PathBuf::from(arg::<String>(a, "pal")?))?;
            to_json(s.pending())
        }),
        "act_frame" => with(state, |s| {
            let refs: Option<Vec<backend::ReferenceSpec>> = arg(a, "references")?;
            to_json(s.act_view_with(
                arg(a, "index")?,
                arg(a, "action")?,
                arg(a, "frame")?,
                &refs.unwrap_or_default(),
            )?)
        }),
        "stage_act_edit" => with(state, |s| {
            let edit: rustygrf_gui_lib::act_editor::ActEdit = arg(a, "edit")?;
            s.stage_act_edit(arg(a, "index")?, arg(a, "action")?, arg(a, "frame")?, &edit)?;
            to_json(s.pending())
        }),
        "stage_gat_edit" => with(state, |s| {
            let edit: rustygrf_gui_lib::gat_editor::GatEdit = arg(a, "edit")?;
            let changed = s.stage_gat_edit(arg(a, "index")?, &edit)?;
            Ok(json!({ "changed": changed, "pending": s.pending() }))
        }),
        "spr_image" => with(state, |s| {
            to_json(s.spr_image(arg(a, "index")?, arg(a, "frame")?)?)
        }),
        "stage_spr_pixels" => with(state, |s| {
            s.stage_spr_pixels(
                arg(a, "index")?,
                arg(a, "frame")?,
                &arg::<String>(a, "pixels")?,
            )?;
            to_json(s.pending())
        }),
        "pal_colors" => with(state, |s| to_json(s.pal_colors(arg(a, "index")?)?)),
        "stage_pal_edit" => with(state, |s| {
            let edit: rustygrf_gui_lib::pal_editor::PalEdit = arg(a, "edit")?;
            s.stage_pal_edit(arg(a, "index")?, &edit)?;
            to_json(s.pending())
        }),
        "text_for_edit" => with(state, |s| to_json(s.text_for_edit(arg(a, "index")?)?)),
        "stage_text_edit" => with(state, |s| {
            s.stage_text_edit(arg(a, "index")?, &arg::<String>(a, "text")?)?;
            to_json(s.pending())
        }),
        "act_layer_at" => with(state, |s| {
            to_json(s.act_layer_at(
                arg(a, "index")?,
                arg(a, "action")?,
                arg(a, "frame")?,
                arg(a, "x")?,
                arg(a, "y")?,
            )?)
        }),
        "hex_page" => with(state, |s| {
            to_json(s.hex_page(arg(a, "index")?, arg(a, "offset")?, arg(a, "len")?)?)
        }),
        "hex_find" => with(state, |s| {
            let pattern: Vec<u8> = arg(a, "pattern")?;
            to_json(s.hex_find(arg(a, "index")?, &pattern, arg(a, "from")?)?)
        }),
        "stage_hex" => with(state, |s| {
            s.stage_hex(arg(a, "index")?, &arg::<Vec<(u64, u8)>>(a, "edits")?)?;
            to_json(s.pending())
        }),
        // the devserver runs headless: it reports the file instead of starting a program
        "open_external" => with(state, |s| {
            to_json(s.export_temp(arg(a, "index")?)?.display().to_string())
        }),
        "act_sound" => with(state, |s| to_json(s.act_sound(&arg::<String>(a, "name")?)?)),
        "reduce_preview" => with(state, |s| to_json(s.reduce_preview(arg(a, "index")?)?)),
        "stage_reduce" => with(state, |s| {
            s.stage_reduce(arg(a, "index")?)?;
            to_json(s.pending())
        }),
        "reduce_images" => {
            let plan = with(state, |s| Ok(s.plan()))?;
            to_json(backend::reduce_images(
                &plan,
                &PathBuf::from(arg::<String>(a, "dst")?),
                arg(a, "minPsnr")?,
                &none,
            )?)
        }
        "stage_act_interval" => with(state, |s| {
            s.stage_act_interval(arg(a, "index")?, arg(a, "action")?, arg(a, "ms")?)?;
            to_json(s.pending())
        }),
        "history" => with(state, |s| {
            let (can_undo, can_redo) = s.history();
            Ok(json!({ "can_undo": can_undo, "can_redo": can_redo }))
        }),
        "undo_change" => with(state, |s| {
            s.undo();
            to_json(s.pending())
        }),
        "redo_change" => with(state, |s| {
            s.redo();
            to_json(s.pending())
        }),
        "pending" => with(state, |s| to_json(s.pending())),
        "restore_draft" => with(state, |s| to_json(s.restore_draft()?)),
        "defer_draft" => with(state, |s| {
            s.defer_draft();
            Ok(Value::Null)
        }),
        "discard_draft" => with(state, |s| {
            s.discard_draft();
            Ok(Value::Null)
        }),
        "discard_pending" => with(state, |s| {
            s.discard_pending();
            Ok(Value::Null)
        }),
        "save_as" => {
            let plan = with(state, |s| Ok(s.plan()))?;
            let req: saving::SaveRequest = arg(a, "req")?;
            to_json(saving::save_as(&plan, &req, true, &none)?)
        }
        "save_archive" => {
            let req: Option<saving::SaveRequest> = arg(a, "req")?;
            to_json(saving::save_in_place(
                state,
                req.unwrap_or_default(),
                &none,
            )?)
        }
        "new_archive" => {
            let dir = std::env::temp_dir().join("rustygrf-new");
            std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
            let stamp = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_millis())
                .unwrap_or(0);
            let path = dir.join(saving::untitled_name(&arg::<String>(a, "kind")?, stamp)?);
            saving::create_empty(&path)?;
            to_json(path.display().to_string())
        }
        "entry_hashes" => with(state, |s| to_json(s.hashes(arg(a, "index")?)?)),
        "compare_with" => {
            let (plan, mode) = with(state, |s| Ok((s.plan(), s.name_mode())))?;
            let other: String = arg(a, "other")?;
            to_json(saving::compare_plan(
                &plan,
                &PathBuf::from(other),
                mode,
                &none,
            )?)
        }
        "make_patch" => {
            let plan = with(state, |s| Ok(s.plan()))?;
            let (old, dst): (String, String) = (arg(a, "old")?, arg(a, "dst")?);
            let method: Option<String> = arg(a, "method")?;
            to_json(saving::patch_plan(
                &plan,
                &PathBuf::from(old),
                &PathBuf::from(dst),
                method.as_deref(),
                &none,
            )?)
        }
        "open_data_folder" => Ok(Value::Null),
        "save_edited" => {
            let plan = with(state, |s| s.edit_plan())?;
            to_json(backend::save_edited(
                &plan,
                &PathBuf::from(arg::<String>(a, "dst")?),
                true,
                &none,
            )?)
        }
        "build_archive" => to_json(backend::build_archive(
            &arg::<BuildRequest>(a, "req")?,
            &none,
        )?),
        "merge_archives" => to_json(backend::merge_archives(
            &arg::<MergeRequest>(a, "req")?,
            &none,
        )?),
        "cancel_job" | "startup_path" | "startup_select" | "window_ready" | "remember_theme"
        | "open_link" => Ok(Value::Null),
        // one browser tab is one window: the page opens the archive in itself
        "open_in_window" => Ok(Value::Bool(false)),
        "close_archive" => {
            *state.lock().map_err(|_| "state is locked")? = None;
            Ok(Value::Null)
        }
        other => Err(format!("unknown command {other}")),
    }
}

struct Request {
    method: String,
    path: String,
    headers: HashMap<String, String>,
    body: Vec<u8>,
}

fn read_request(stream: &TcpStream) -> Option<Request> {
    let mut r = BufReader::new(stream);
    let mut line = String::new();
    r.read_line(&mut line).ok()?;
    let mut parts = line.split_whitespace();
    let (method, path) = (parts.next()?.to_string(), parts.next()?.to_string());
    let mut headers = HashMap::new();
    loop {
        line.clear();
        r.read_line(&mut line).ok()?;
        let l = line.trim_end();
        if l.is_empty() {
            break;
        }
        let (k, v) = l.split_once(':')?;
        headers.insert(k.trim().to_ascii_lowercase(), v.trim().to_string());
    }
    let len: usize = headers
        .get("content-length")
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);
    if len > 16 * 1024 * 1024 {
        return None;
    }
    let mut body = vec![0; len];
    r.read_exact(&mut body).ok()?;
    Some(Request {
        method,
        path,
        headers,
        body,
    })
}

fn respond(mut s: &TcpStream, status: &str, mime: &str, body: &[u8]) {
    let head = format!(
        "HTTP/1.1 {status}\r\nContent-Type: {mime}\r\nContent-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n",
        body.len()
    );
    let _ = s.write_all(head.as_bytes());
    let _ = s.write_all(body);
}

fn mime_of(p: &Path) -> &'static str {
    match p.extension().and_then(|e| e.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("png") => "image/png",
        Some("svg") => "image/svg+xml",
        Some("ftl") => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

fn handle(stream: TcpStream, ui: &Path, state: &State, port: u16) {
    let Some(req) = read_request(&stream) else {
        return respond(&stream, "400 Bad Request", "text/plain", b"bad request");
    };
    let host_ok = req
        .headers
        .get("host")
        .is_some_and(|h| [format!("127.0.0.1:{port}"), format!("localhost:{port}")].contains(h));
    if !host_ok {
        return respond(&stream, "403 Forbidden", "text/plain", b"bad host");
    }
    if req.method == "POST" && req.path == "/invoke" {
        if !req.headers.contains_key("x-rgrf-dev") {
            return respond(&stream, "403 Forbidden", "text/plain", b"missing header");
        }
        let out = serde_json::from_slice::<Value>(&req.body)
            .map_err(|e| e.to_string())
            .and_then(|v| {
                let cmd = v["cmd"].as_str().ok_or("no cmd")?.to_string();
                invoke(state, &cmd, &v["args"])
            });
        let j = match out {
            Ok(v) => json!({ "ok": v }),
            Err(e) => json!({ "error": e }),
        };
        return respond(
            &stream,
            "200 OK",
            "application/json",
            j.to_string().as_bytes(),
        );
    }
    if req.method != "GET" {
        return respond(
            &stream,
            "405 Method Not Allowed",
            "text/plain",
            b"GET or POST /invoke",
        );
    }
    let rel = req.path.split('?').next().unwrap_or("/");
    let rel = if rel == "/" { "/index.html" } else { rel };
    if rel == "/mock.js" {
        return respond(
            &stream,
            "200 OK",
            mime_of(Path::new("a.js")),
            BRIDGE_JS.as_bytes(),
        );
    }
    let rel = rel.trim_start_matches('/');
    if rel.split('/').any(|c| c == ".." || c.is_empty()) {
        return respond(&stream, "403 Forbidden", "text/plain", b"forbidden");
    }
    let file = ui.join(rel);
    match std::fs::read(&file) {
        Ok(b) => respond(&stream, "200 OK", mime_of(&file), &b),
        Err(_) => respond(&stream, "404 Not Found", "text/plain", b"not found"),
    }
}

fn main() {
    let mut args = std::env::args().skip(1);
    let ui = PathBuf::from(args.next().unwrap_or_else(|| "ui".into()));
    let port: u16 = args.next().and_then(|p| p.parse().ok()).unwrap_or(8766);
    let listener = TcpListener::bind(("127.0.0.1", port)).expect("cannot listen");
    let state: State = Arc::new(Mutex::new(None));
    println!(
        "devserver: http://127.0.0.1:{port}/ (ui from {})",
        ui.display()
    );
    for stream in listener.incoming().flatten() {
        let (ui, state) = (ui.clone(), Arc::clone(&state));
        std::thread::spawn(move || handle(stream, &ui, &state, port));
    }
}
